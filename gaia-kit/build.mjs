// Builds gaia-kit/src → gaia-kit/v1/*.js (plain JS, no Babel needed at runtime, works on file://).
// Usage: ./build.sh   (maintainers only — story authors never need to run this)
import fs from "fs";
import path from "path";
import { execFileSync } from "child_process";
import { fileURLToPath } from "url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(HERE, "src");
const OUT = path.join(HERE, "v1");
const VERSION = "1.0.0";
const ESBUILD = ["--yes", "esbuild@0.28.2", "--loader=jsx", "--jsx-factory=React.createElement", "--jsx-fragment=React.Fragment", "--target=es2020", "--log-level=warning"];
const HOOKS = "const { useState, useEffect, useLayoutEffect, useRef, useCallback, useMemo } = React;";
const INTERNAL = new Set(["fontLink", "styleEl", "eduStyleEl", "NEXT", "WAIT", "JUMPED", "waitHandler", "cardHandler", "branchHandler", "WAIT_KEYS", "waitKeySeq", "STEP_TYPES", "EXPANDERS", "MODULES", "USE_CASES"]);

const BUNDLES = [
  { name: "core", files: ["core/00-styles.js", "core/01-tokens.jsx", "core/02-primitives.jsx", "core/03-composer.jsx", "core/04-thread-cards.jsx", "core/05-typing.jsx", "core/06-thread-extras.jsx", "core/07-engine.js", "core/08-shell.jsx", "core/09-modular.js", "core/10-modular-ui.jsx"] },
  { name: "screens", files: ["screens/screens.jsx"] },
  { name: "panels", files: ["panels/panels.jsx"] },
  { name: "onboarding-cards", files: ["onboarding-cards/00-styles.js", "onboarding-cards/cards.jsx"] },
];

const topLevelNames = (code) => {
  const names = [];
  const re = /^(?:async\s+)?(?:function\s+([A-Za-z_$][\w$]*)|const\s+([A-Za-z_$][\w$]*)\s*=|class\s+([A-Za-z_$][\w$]*)|let\s+([A-Za-z_$][\w$]*))/gm;
  let m;
  while ((m = re.exec(code))) names.push(m[1] || m[2] || m[3] || m[4]);
  return names;
};

const transform = (code, label) => {
  try {
    return execFileSync("npx", ESBUILD, { input: code, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  } catch (e) {
    console.error("esbuild failed for " + label);
    process.exit(1);
  }
};

const header = (name) => `/* gaia-kit v${VERSION} — ${name}. GENERATED by gaia-kit/build.mjs from gaia-kit/src. Do not edit by hand. */\n`;

fs.mkdirSync(OUT, { recursive: true });
let coreExports = [];
for (const b of BUNDLES) {
  const body = b.files.map((f) => `/* ── ${f} ── */\n` + fs.readFileSync(path.join(SRC, f), "utf8")).join("\n\n");
  const names = topLevelNames(body).filter((n) => !INTERNAL.has(n));
  let prelude;
  if (b.name === "core") {
    coreExports = names.concat(["registerStep", "StoryMachine"]).filter((v, i, a) => a.indexOf(v) === i);
    prelude = `${HOOKS}
const GaiaKit = (window.GaiaKit = window.GaiaKit || {});
const ASSET_BASE = new URL("assets/", document.currentScript.src).href;
`;
  } else {
    const clash = names.filter((n) => coreExports.includes(n));
    if (clash.length) { console.error(`${b.name}: names already defined in core: ${clash.join(", ")}`); process.exit(1); }
    prelude = `${HOOKS}
const GaiaKit = window.GaiaKit;
if (!GaiaKit || !GaiaKit.version) throw new Error("Load gaia-kit.core.js before gaia-kit.${b.name}.js");
const { ${coreExports.join(", ")} } = GaiaKit;
`;
  }
  const exportsList = b.name === "core" ? coreExports : names;
  const postlude = `\nObject.assign(GaiaKit, { ${exportsList.join(", ")} });\n` +
    (b.name === "core" ? `GaiaKit.version = "${VERSION}";\n` : "") +
    `GaiaKit.modules = (GaiaKit.modules || []).concat("${b.name}");\n`;
  const js = transform(`(function () {\n"use strict";\n${prelude}\n${body}\n${postlude}})();\n`, b.name);
  const file = path.join(OUT, `gaia-kit.${b.name}.js`);
  fs.writeFileSync(file, header(b.name) + js);
  console.log(`v1/gaia-kit.${b.name}.js  ${(fs.statSync(file).size / 1024).toFixed(1)} KB  (${exportsList.length} exports)`);
}

// Brands
fs.mkdirSync(path.join(OUT, "brands"), { recursive: true });
for (const f of fs.readdirSync(path.join(SRC, "brands")).filter((f) => f.endsWith(".jsx"))) {
  const code = fs.readFileSync(path.join(SRC, "brands", f), "utf8");
  const js = transform(`(function () {\n"use strict";\n${code}\n})();\n`, f);
  const out = path.join(OUT, "brands", f.replace(/\.jsx$/, ".js"));
  fs.writeFileSync(out, header("brand " + f) + js);
  console.log(`v1/brands/${path.basename(out)}  ${(fs.statSync(out).size / 1024).toFixed(1)} KB`);
}
